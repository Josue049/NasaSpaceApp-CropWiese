'use strict';
const assert=require('node:assert/strict');
const {evaluateRiceCriteria,weightsOrThrow}=require('../src/rice_criteria_proposal');
const approx=(a,b)=>assert.ok(Math.abs(a-b)<1e-10,`${a} != ${b}`);
const w=weightsOrThrow({C1:50,C2:40,C7:10}); approx(w.C1,0.5);approx(w.C2,0.4);approx(w.C7,0.1);
assert.throws(()=>weightsOrThrow({C1:0,C2:0,C7:0}));
const inp={etc_mm:600,water_satisfaction:0.9,drought_fraction:0.1,complete_fraction:0.9,complete_fraction_cold:0.8,flowering_heat_fraction:0.7,sequence:['frijol','arroz','frijol','arroz'],prior_crop_id:'arroz',family_by_id:{arroz:'Poaceae',frijol:'Fabaceae'}};
const missing=evaluateRiceCriteria(inp);
assert.equal(missing.criteria.C1.score,null);
assert.equal(missing.complete_score,null);
assert.equal(missing.status,'EXPLORATORIO_NO_RECOMENDACION');
assert.equal(missing.may_label_as_recommendation,false);
assert.ok(missing.coverage_weight < 1);
assert.ok(missing.warnings.some(x=>x.includes('C1')));
const full=evaluateRiceCriteria({...inp,irrigation_supply_mm:500,irrigation_requirement_mm:1000});
approx(full.criteria.C1.score,0.5);
assert.ok(full.complete_score!==null);
assert.equal(full.may_label_as_recommendation,false);
assert.equal(full.criteria.C2.score,0.6*0.85+0.4*0.3);
const nullC2=evaluateRiceCriteria({...inp,flowering_heat_fraction:null});
assert.equal(nullC2.criteria.C2.score,null);
const repeat=evaluateRiceCriteria({...inp,sequence:['arroz','arroz','arroz','arroz']});
assert.ok(repeat.criteria.C7.score < missing.criteria.C7.score);
console.log('OK: 9 comprobaciones de integridad y casos limite (datos sintéticos).');
