'use strict';
const assert = require('node:assert/strict');
const {priorityWeights, total, CRITERIA} = require('../src/engine');
const eq = (a,b) => Math.abs(a-b) < 1e-10;
const base = {slope:10,soil:{},input:{priorities:{protect_soil:3,water:3,resilience:3,pests:3,income:3,low_cost:3}}};
const legacy = priorityWeights(base);
assert(eq(Object.values(legacy).reduce((a,b)=>a+b,0),1));
assert(legacy.thermal > 0 && legacy.soil_fit > 0);
const ctx = {...base,input:{...base.input,weighting_model:'grouped_v1',group_priorities:{soil:30,water:35,rotation:20,economy:15}}};
const w = priorityWeights(ctx);
assert(eq(Object.values(w).reduce((a,b)=>a+b,0),1));
assert(eq(w.erosion,.15) && eq(w.organic_n,.15));
assert(eq(w.water,.35) && eq(w.pest,.20));
assert(eq(w.market,.075) && eq(w.low_cost,.075));
assert(eq(w.resilience,0) && eq(w.thermal,0) && eq(w.soil_fit,0));
assert(eq(total(Object.fromEntries(CRITERIA.map(k=>[k,1])),w),100));
const waterOnly = priorityWeights({...ctx,input:{...ctx.input,group_priorities:{soil:0,water:100,rotation:0,economy:0}}});
assert(eq(waterOnly.water,1));
assert(eq(Object.values(waterOnly).filter(v=>v>0).length,1));
assert.throws(()=>priorityWeights({...ctx,input:{...ctx.input,group_priorities:{soil:0,water:0,rotation:0,economy:0}}}),/al menos una/);
assert.throws(()=>priorityWeights({...ctx,input:{...ctx.input,group_priorities:{soil:-1}}}),/fuera de rango/);
const noSoil = priorityWeights({...ctx,soil:null});
assert(eq(noSoil.erosion,.15));
console.log('OK: 10 comprobaciones de ponderación aislada (sin climate.js real)');
